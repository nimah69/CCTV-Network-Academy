import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
const html=fs.readFileSync("index.html","utf8");
const bankSource=fs.readFileSync("js/chapter-labs.js","utf8");
const uiSource=fs.readFileSync("js/chapter-lab-ui.js","utf8");
assert.ok(html.includes('<script src="js/chapter-labs.js"></script>'));
assert.ok(html.includes('<script src="js/chapter-lab-ui.js"></script>'));
assert.ok(html.includes('state.view==="chapterLab"'));
new vm.Script(uiSource,{filename:"js/chapter-lab-ui.js"});
const sandbox={window:{},console};vm.createContext(sandbox);vm.runInContext(bankSource,sandbox,{filename:"js/chapter-labs.js"});
const groups=sandbox.window.CCTVChapterLabs;
assert.equal(groups.length,14);assert.equal(groups.flat().length,70);
const distribution=[0,0,0],banned=/(درست|غلط|بهترین|اشتباه|مناسب‌تر)/;
groups.forEach((scenarios,c)=>{assert.equal(scenarios.length,5);scenarios.forEach((s,i)=>{
 assert.ok(s.title&&s.context&&s.check&&s.why&&s.clue);
 assert.ok(!/^قدم بعدی/.test(s.clue),`Scenario ${c+1}:${i+1} repeats the next-step prefix`);
 assert.equal(s.options.length,3);assert.ok(s.answer>=0&&s.answer<3);distribution[s.answer]++;
 const correct=s.options[s.answer],visible=[s.title,s.context,s.simulator.intro].join(" ");
 assert.ok(!visible.includes(correct)&&!visible.includes(correct.slice(0,25)),`Scenario ${c+1}:${i+1} leaks the answer before response`);
 assert.ok(!s.simulator.prompt);assert.equal(s.simulator.trials.length,3);
 const observations=s.simulator.trials.map(t=>t.observation);assert.equal(new Set(observations).size,3);assert.ok(observations.every(t=>t.length>0&&!banned.test(t)));
 assert.equal(s.nodes.length,3);
});});
assert.ok(distribution.every(n=>n/70>=0.2&&n/70<=0.4),`Answer distribution outside 20–40%: ${distribution}`);
assert.ok(uiSource.includes("function advanceLabSimulator"));assert.ok(uiSource.includes("function setLabSimulatorTrial"));assert.ok(uiSource.includes("function resetLabSimulator"));
assert.ok(!uiSource.includes("setLabSimulatorOutcome"));assert.ok(!uiSource.includes("labSimOutcome"));assert.ok(uiSource.includes("شبیه‌ساز برای این تمرین موجود نیست"));
const context={window:{CCTVChapterLabs:[]},state:{chapter:0,labScenario:0,labDraft:null,labSimStep:0,labSimTrial:null,progress:{labs:{},done:[]}},chapters:[{title:"فصل آزمایشی"}],saveProgress(){},render(){},alert(){},console};
vm.createContext(context);vm.runInContext(uiSource,context,{filename:"js/chapter-lab-ui.js"});context.window.CCTVChapterLabs=[groups[0]];
context.advanceLabSimulator(1);assert.equal(context.state.labSimStep,1);context.setLabSimulatorTrial(2);assert.equal(context.state.labSimTrial,2);assert.equal(context.state.labSimStep,2);
context.setLabSimulatorTrial(3);assert.equal(context.state.labSimTrial,2);
context.state.labDraft=groups[0][0].answer;context.runChapterLabScenario();assert.equal(context.state.progress.labs["0:0"].correct,true);
assert.deepEqual(Object.keys(context.state.progress.labs["0:0"]).sort(),["answer","at","attempts","checked","correct"].sort());
context.retryChapterLabScenario(0);assert.equal(context.state.progress.labs["0:0"],undefined);
const start=html.indexOf("<script>"),end=html.lastIndexOf("</script>");assert.ok(start>=0&&end>start);new vm.Script(html.slice(start+8,end),{filename:"index.html:inline-script"});
console.log("Chapter labs checks passed: 70 scenarios, answer privacy, trial-based simulator, and progress persistence.");
