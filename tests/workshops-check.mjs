import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
const html=fs.readFileSync("workshops.html","utf8");
assert.ok(html.includes('<html lang="fa" dir="rtl">'),"Workshop page must be Persian RTL");
for(const id of ["trouble","topology","poe","subnet","storage","cable","security","capstone"]) assert.ok(html.includes('id="'+id+'"'),"Missing workshop: "+id);
for(const id of ["scenarioChoices","checkTopology","calcPoe","calcSubnet","calcStorage","recommendCable","scoreSecurity","buildReport","downloadReport","printReport"]) assert.ok(html.includes('id="'+id+'"'),"Missing interaction: "+id);
const scripts=[...html.matchAll(/<script>([\s\S]*?)<\/script>/gi)].map(m=>m[1]);
assert.equal(scripts.length,1,"Expected one workshop application script");
new vm.Script(scripts[0],{filename:"workshops.html:inline-script"});
const scenarioBlock=scripts[0].match(/const scenarios=\[([\s\S]*?)\n\];/);
assert.ok(scenarioBlock,"Scenario bank must exist");
assert.equal((scenarioBlock[1].match(/title:"/g)||[]).length,12,"Expected 12 troubleshooting scenarios");
assert.ok(html.includes("localStorage"),"Workshop progress should persist locally");
assert.ok(html.includes('src="./js/calculations.js"'),"Shared tested calculation module must load before workshop code");
assert.ok(html.includes("function requiredNumber"),"Numeric fields must reject empty and invalid values");
assert.ok(html.includes('id="poeResult" aria-live="polite"'),"PoE validation messages must be announced politely");
assert.ok(html.includes('id="subnetResult" aria-live="polite"'),"Subnet validation messages must be announced politely");
assert.ok(html.includes("@media(max-width:399px)"),"Small-phone responsive overrides must exist");
assert.ok(!html.includes("https://") && !html.includes("http://"),"Workshop page should not require external services");
console.log("Interactive workshops checks passed: 8 workshops, 12 troubleshooting scenarios, script syntax and key interactions.");

assert.equal((html.match(/class="lab-schematic"/g)||[]).length,8,"Every workshop should include a schematic panel");
assert.equal((html.match(/<button[^>]*data-sim-toggle(?:\s|>)/g)||[]).length,7,"Seven schematic animation buttons should be present; PoE uses its input-driven simulator");
assert.equal((html.match(/<button class="sim-reset" type="button" data-sim-reset>/g)||[]).length,8,"Every schematic simulator must have a visible reset button");
assert.ok(html.includes('document.querySelectorAll("[data-sim-reset]")'),"Schematic reset buttons must be wired to reset their workshop");
assert.ok(html.includes('id="runPoeSimulation"'),"PoE must use an input-driven simulation control rather than animation-only flow");
assert.ok(html.includes("prefers-reduced-motion"),"Schematic animation must respect reduced-motion preferences");
assert.ok(html.includes('aria-pressed="false"'),"Simulator controls must expose accessible pressed state");
assert.ok(html.includes("اجرای شبیه‌سازی تعاملی"),"Simulator controls must be clearly labeled and actionable in Persian");
