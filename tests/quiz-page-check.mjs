import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
const html=fs.readFileSync(path.join(process.cwd(),"index.html"),"utf8");
assert.match(html,/function quizHTML\(comprehensive=false\)/);
const start=html.indexOf("function quizHTML(comprehensive=false)");
const end=html.indexOf("function reviewCardHTML",start);
const renderer=html.slice(start,end);
assert.match(renderer,/const q=qs\[index\]/,"Only the active question should be rendered in the quiz page");
assert.ok(!renderer.includes('qs.map((q,i)=>`<div class="quiz-question"'), "The active quiz page must not render every question at once");
assert.match(renderer,/quiz-progress-meta/,"Progress and current question must be visible");
assert.match(renderer,/selectQuizAnswer\(index,value\)/,"Answers must be recorded");
assert.match(renderer,/state\.quizMode==="practice"&&selected/,"Feedback must be limited to practice mode");
assert.match(renderer,/setQuizMode\(&#39;practice&#39;\)/,"Practice mode control must be available");
assert.match(renderer,/setQuizMode\(&#39;exam&#39;\)/,"Exam mode control must be available");
assert.match(renderer,/state\.quizMode==="exam"/,"Exam mode must suppress in-question feedback");
assert.match(html,/function setQuizMode\(mode\)/,"Quiz mode selection must be persisted");
assert.match(renderer,/previousQuizQuestion/,"Previous navigation must be available");
assert.match(renderer,/nextQuizQuestion/,"Next navigation must be available");
assert.match(renderer,/disabled aria-disabled="true"/,"Moving to the next question must be disabled until an answer is selected");
assert.match(renderer,/ابتدا پاسخ بده · پرسش بعدی/,"The disabled next action must explain why it cannot be used");
assert.match(renderer,/state\.quizAnswers\[index\]/,"Answers must persist while moving between questions");
assert.match(renderer,/state\.quizSubmitted/,"Final summary must be a distinct finished state");
assert.match(html,/state\.progress\.wrongQuestions\.push\(\.\.\.wrong\)/,"Wrong-answer review storage must remain intact");
assert.match(html,/const storeKey="cctvAcademyProgressV1"/,"Existing progress key must not change");
console.log(JSON.stringify({status:"passed",singleQuestionRenderer:true,feedbackPerQuestion:true,progressKeyPreserved:true},null,2));
