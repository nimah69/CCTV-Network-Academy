import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
const root=process.cwd();
const manifest=fs.readFileSync(path.join(root,"android/app/src/main/AndroidManifest.xml"),"utf8");
const activity=fs.readFileSync(path.join(root,"android/app/src/main/java/ir/nimah69/cctvnetworkacademy/MainActivity.java"),"utf8");
const gradle=fs.readFileSync(path.join(root,"android/app/build.gradle"),"utf8");
const workflow=fs.readFileSync(path.join(root,".github/workflows/offline-apk-ci.yml"),"utf8");
const bundler=fs.readFileSync(path.join(root,"scripts/bundle-android-assets.sh"),"utf8");
const sw=fs.readFileSync(path.join(root,"service-worker.js"),"utf8");
const index=fs.readFileSync(path.join(root,"index.html"),"utf8");
const workshops=fs.readFileSync(path.join(root,"workshops.html"),"utf8");
const font=path.join(root,"fonts/Vazirmatn-Variable.woff2");
const license=fs.readFileSync(path.join(root,"fonts/OFL.txt"),"utf8");
assert.match(manifest,/android:allowBackup="false"/);
assert.match(activity,/file:\/\/\/android_asset\/academy\//,"Internal offline URLs must remain in WebView");
assert.match(activity,/Intent\.ACTION_VIEW/,"External HTTP/HTTPS links must open in an external browser");
assert.match(activity,/path\.contains\("\.\."\)/,"Local file URLs must not traverse outside the academy asset directory");
assert.match(activity,/equalsIgnoreCase\(scheme\)/,"External routing must check the URL scheme");
assert.match(activity,/CCTVAcademyHandleBack/,"Native Back must keep using the route handler");
assert.match(gradle,/targetSdk 34/,"Target SDK should remain at the reviewed conservative level");
assert.match(workflow,/bash scripts\/bundle-android-assets\.sh/,"CI must use the same bundler as local builds");
assert.match(bundler,/cp "\$ROOT_DIR\/js\/"\*\.js/);
assert.match(bundler,/cmp -s/,"Bundler must verify copied assets");
assert.ok(fs.existsSync(font),"Local variable font must be present");
assert.ok(fs.statSync(font).size<300*1024,"Bundled font must stay below 300 KB");
assert.match(license,/SIL OPEN FONT LICENSE Version 1\.1/);
assert.match(index,/Vazirmatn-Variable\.woff2/);
assert.match(workshops,/Vazirmatn-Variable\.woff2/);
assert.match(sw,/\.\/fonts\/Vazirmatn-Variable\.woff2/);
assert.match(sw,/cctv-academy-static-v2026-10-16-6/);
console.log(JSON.stringify({status:"passed",fontBytes:fs.statSync(font).size,targetSdk:34,allowBackup:false,externalLinks:true},null,2));
